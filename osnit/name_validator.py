_HE_PREFIX_1 = set("הבכלמוש")
_HE_PREFIX_2 = {"בה", "לה", "מה", "כה", "וה", "שה", "וב", "ול", "ומ", "וכ", "וש"}


def _has_prefixed_stop_stem(tok: str) -> bool:
    """Checks if a Hebrew token is a preposition/article + institutional/boilerplate stem."""
    if len(tok) >= 5 and tok[0] in _HE_PREFIX_1 and tok[1:] in PREFIXABLE_INSTITUTIONAL_STEMS:
        return True
    if len(tok) >= 6 and tok[:2] in _HE_PREFIX_2 and tok[2:] in PREFIXABLE_INSTITUTIONAL_STEMS:
        return True
    return False


def has_non_person_stop_token(text: str) -> bool:
    """
    Checks whether a single word or multi-word string contains any institutional,
    government, corporate, geographic, calendar, or form-boilerplate stop token/phrase.
    Safe to call on 1-word first/last name parts as well as full names.
    """
    if not text or not isinstance(text, str):
        return True
    s = squash(clean(text)).strip(" ,.;:-_|/\\")
    if not s:
        return True
    folded_full = re.sub(r"\s+", " ", fold(re.sub(r"[\"'׳״\-]+", " ", s))).strip()
    if not folded_full or folded_full in STOP_PHRASES_EXACT:
        return True
    for rw in s.split():
        rw_clean = rw.strip(".,")
        if not rw_clean:
            continue
        rw_f = fold(rw_clean)
        core_f = fold(rw_clean.strip("\"'׳״-"))
        if rw_f in STOP_TOKENS_UNCONDITIONAL or core_f in STOP_TOKENS_UNCONDITIONAL:
            return True
        if _has_prefixed_stop_stem(core_f):
            return True
        if re.match(r"^ה?תש[א-ת\"'״׳]{1,6}$", rw_f):
            return True
        for sub_part in re.split(r"[\-]+", rw_clean):
            sp_f = fold(sub_part.strip("\"'׳״."))
            if sp_f and (sp_f in STOP_TOKENS_UNCONDITIONAL or _has_prefixed_stop_stem(sp_f)):
                return True
    return False


def is_valid_person_name(name: str) -> bool:
    """
    Comprehensive validation gate for person names.
    Ensures `name`:
    1. Contains 2 to 4 words (at least first + last name).
    2. Contains no digits, abnormal punctuation, or lone single letters (unless initial with `'`).
    3. Does not match any exact stop phrase (cities, ministries, calendar expressions, boilerplate).
    4. Contains no unconditional stop-word token (or prefixed institutional stem).
    5. Does not combine calendar/month tokens in a temporal pattern (e.g. 'אדר ב\\'', 'מנחם אב', 'ניסן אייר').
    """
    if not name or not isinstance(name, str):
        return False
    s = squash(clean(name)).strip(" ,.;:-_|/\\")
    if len(s) < 3 or len(s) > 65:
        return False
    # Reject digits or code/formatting symbols
    if re.search(r"[\d@#$%^&*+=<>~`|\\/\[\]{}()_:;!?]", s):
        return False
    # Reject mixed Hebrew and Latin scripts in the same name (e.g. OCR noise "nny דביר")
    if re.search(r"[א-ת]", s) and re.search(r"[A-Za-z]", s):
        return False
    # Must contain at least 3 letters
    if len(re.findall(r"[A-Za-zא-ת]", s)) < 3:
        return False

    folded_full = fold(re.sub(r"[\"'׳״\-]+", " ", s))
    folded_full = re.sub(r"\s+", " ", folded_full).strip()
    if not folded_full or folded_full in STOP_PHRASES_EXACT:
        return False

    # Also check raw whitespace tokens before stripping apostrophes (to catch initials like "א'")
    raw_words = [w.strip(".,") for w in s.split() if w.strip(".,")]
    # If a 1-word hyphenated string was passed (e.g. "תל-אביב"), raw_words has length 1 -> rejected
    if not (2 <= len(raw_words) <= 4):
        return False

    toks = []
    single_letter_count = 0
    for rw in raw_words:
        # Strip outer quotes/punctuation
        core = rw.strip("\"'׳״-.")
        if not core:
            return False
        if len(core) == 1:
            single_letter_count += 1
        toks.append(fold(core))

    # At most 1 single-letter initial is allowed in a 2-4 word name (e.g. "Roni A", "ג. דן", "ישראל א' כהן")
    if single_letter_count > 1 or single_letter_count >= len(toks):
        return False

    # Reject identical repeated tokens (e.g., "כהן כהן", "משרד משרד")
    if len(set(toks)) == 1:
        return False

    # Check contiguous sub-phrases (both whitespace-based and hyphen-expanded) against STOP_PHRASES_EXACT
    expanded_toks = folded_full.split()
    for token_seq in (toks, expanded_toks):
        for i in range(len(token_seq)):
            for j in range(i + 2, len(token_seq) + 1):
                sub = " ".join(token_seq[i:j])
                if sub in STOP_PHRASES_EXACT:
                    return False

    # Check each token (and hyphen sub-parts) against unconditional stop words and prefixed institutional stems
    if has_non_person_stop_token(s):
        return False

    # Contextual calendar check: if any token is an ambiguous month/day name (e.g. סיוון, אדר, ניסן, אב),
    # reject if another token is a calendar partner (e.g. "אדר ב'", "מנחם אב" when in calendar context, "ניסן אייר")
    if any(t in AMBIGUOUS_CALENDAR_TOKENS for t in expanded_toks):
        other_cal = sum(1 for t in expanded_toks if t in CALENDAR_CONTEXT_PARTNERS)
        if other_cal >= 2:
            # Allow genuine name "מנחם אב..." only if 2nd token is not literally "אב" alone ("מנחם אב" = month of Av)
            return False
        if single_letter_count > 0:
            # e.g., "אדר א'", "אדר ב'"
            return False

    return True


def purge_invalid_persons(store) -> dict:
    """
    Scans all existing 'person' entities in `store` and deletes any entity
    whose display name fails `is_valid_person_name`.
    Returns {"checked": int, "removed": int, "removed_names": list}.
    """
    rows = store.q("SELECT id, display FROM entities WHERE type='person'")
    removed_ids = []
    removed_names = []
    for r in rows:
        disp = r["display"] or ""
        if not is_valid_person_name(disp):
            removed_ids.append(r["id"])
            removed_names.append(disp)
    for eid in removed_ids:
        store.delete_entity(eid)
    return {
        "checked": len(rows),
        "removed": len(removed_ids),
        "removed_names": removed_names,
    }
